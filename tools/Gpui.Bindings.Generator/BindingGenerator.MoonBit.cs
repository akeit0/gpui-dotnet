using System.Text;

internal static partial class BindingGenerator
{
    private const string MoonHeader = "// @generated by Gpui.Bindings.Generator. Do not edit.";

    private static int MoonValueKind(string value) => value switch
    {
        "none" => 0, "f32" => 1, "u32" => 2, "callback" => 3,
        "u64" => 4, "f32x2" => 5, "data" => 6,
        _ => throw new InvalidOperationException($"Unsupported MoonBit value kind '{value}'."),
    };

    private static void MoonConstant(StringBuilder builder, string name, string type, string value)
    {
        builder.AppendLine("///|");
        builder.AppendLine($"pub const {name} : {type} = {value}");
        builder.AppendLine();
    }

    private static void MoonMatch(StringBuilder builder, string name, string type,
        IEnumerable<(int Id, string Value)> entries, string fallback)
    {
        builder.AppendLine("///|");
        builder.AppendLine($"pub fn {name}(id : Int) -> {type} {{");
        builder.AppendLine("  match id {");
        foreach (var (id, value) in entries)
        {
            builder.AppendLine($"    {id} => {value}");
        }
        builder.AppendLine($"    _ => {fallback}");
        builder.AppendLine("  }");
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static string GenerateMoonBitProtocol(BindingSchema schema, ulong hash)
    {
        var b = new StringBuilder().AppendLine(MoonHeader).AppendLine();
        MoonConstant(b, "SCHEMA_VERSION", "Int", schema.SchemaVersion.ToString());
        MoonConstant(b, "SCHEMA_HASH", "UInt64", $"0x{hash:X16}UL");
        foreach (var capability in schema.Capabilities)
            MoonConstant(b, $"CAPABILITY_{UpperSnake(capability)}", "UInt64", $"0x{CapabilityBit(schema, capability):X16}UL");
        foreach (var component in schema.Components)
            MoonConstant(b, $"COMPONENT_{UpperSnake(component.Name)}", "Int", component.Id.ToString());
        foreach (var operation in schema.Operations)
            MoonConstant(b, $"OP_{UpperSnake(operation.Name)}", "Int", operation.Id.ToString());
        foreach (var resource in schema.Resources)
        {
            MoonConstant(b, $"RESOURCE_{UpperSnake(resource.Name)}", "Int", resource.Id.ToString());
            foreach (var command in resource.Commands)
                MoonConstant(b, $"COMMAND_{UpperSnake(resource.Name)}_{UpperSnake(command.Name)}", "Int", command.Id.ToString());
        }
        foreach (var controlEvent in schema.ControlEvents)
            MoonConstant(b, $"EVENT_{UpperSnake(controlEvent.Name)}", "Int", controlEvent.Id.ToString());
        foreach (var enumeration in schema.Enums)
            foreach (var variant in enumeration.Variants)
                MoonConstant(b, $"{UpperSnake(enumeration.Name)}_{UpperSnake(variant.Name)}", "UInt", variant.Value + "U");

        MoonMatch(b, "component_capabilities", "UInt64", schema.Components.Select(c => (c.Id, $"0x{CapabilityMask(schema, c.Capabilities):X16}UL")), "0UL");
        MoonMatch(b, "component_known", "Bool", schema.Components.Select(c => (c.Id, "true")), "false");
        MoonMatch(b, "component_children", "Bool", schema.Components.Select(c => (c.Id, c.Children ? "true" : "false")), "false");
        MoonMatch(b, "component_requires_data", "Bool", schema.Components.Select(c => (c.Id, c.DataRequired ? "true" : "false")), "false");
        MoonMatch(b, "component_accepts_data", "Bool", schema.Components.Select(c => (c.Id, c.Data == "utf8" ? "true" : "false")), "false");
        MoonMatch(b, "operation_kind", "Int", schema.Operations.Select(o => (o.Id, MoonValueKind(o.Value).ToString())), "-1");
        MoonMatch(b, "operation_capability", "UInt64", schema.Operations.Select(o => (o.Id, $"0x{CapabilityBit(schema, o.Requires):X16}UL")), "0UL");
        MoonMatch(b, "operation_payload", "Bool", schema.Operations.Select(o => (o.Id, o.Payload == "event" ? "true" : "false")), "false");
        return b.ToString().TrimEnd() + "\n";
    }

    // The MoonBit authoring API uses semantic names, not C# managedMethod conventions. Keeping
    // all writes in Frame gives a coarse FFI boundary even when the surface is fluent.
    private static string GenerateMoonBitElements(BindingSchema schema)
    {
        var b = new StringBuilder().AppendLine(MoonHeader).AppendLine();
        foreach (var operation in schema.Operations)
        {
            if (operation.Name is "element_owner" or "resource_owner" or "list_renderer" or "on_click" or "on_shortcut")
                continue;
            var (parameters, body) = operation.Value switch
            {
                "none" => ("", $"self.op_none(@protocol.OP_{UpperSnake(operation.Name)})"),
                "u32" => (", value : UInt", $"self.op_u32(@protocol.OP_{UpperSnake(operation.Name)}, value)"),
                "u64" => (", value : UInt64", $"self.op_u64(@protocol.OP_{UpperSnake(operation.Name)}, value)"),
                "f32" => (", value : Float", $"self.op_f32(@protocol.OP_{UpperSnake(operation.Name)}, value)"),
                "f32x2" => (", x : Float, y : Float", $"self.op_f32x2(@protocol.OP_{UpperSnake(operation.Name)}, x, y)"),
                "data" when operation.ManagedMethod?.Kind == "string" || operation.Name == "focus_target"
                    => (", value : String", $"self.op_text(@protocol.OP_{UpperSnake(operation.Name)}, value)"),
                "data" => (", value : Bytes", $"self.op_data(@protocol.OP_{UpperSnake(operation.Name)}, value)"),
                "callback" => (", handler : (EventContext, Event) -> Unit", $"self.on(@protocol.OP_{UpperSnake(operation.Name)}, handler)"),
                _ => throw new InvalidOperationException($"Unknown operation value '{operation.Value}'."),
            };
            b.AppendLine("///|");
            b.AppendLine($"pub fn Element::{operation.Name}(self : Element{parameters}) -> Element {{");
            b.AppendLine($"  {body}");
            b.AppendLine("}");
            b.AppendLine();
        }
        return b.ToString().TrimEnd() + "\n";
    }

    private static string GenerateMoonBitExtension(ExtensionSchema schema, ulong hash)
    {
        var b = new StringBuilder().AppendLine(MoonHeader).AppendLine();
        MoonConstant(b, "EXTENSION_ID", "String", System.Text.Json.JsonSerializer.Serialize(schema.ExtensionId));
        MoonConstant(b, "SCHEMA_VERSION", "UInt", schema.SchemaVersion + "U");
        MoonConstant(b, "SCHEMA_HASH", "UInt64", $"0x{hash:X16}UL");
        foreach (var component in schema.Components)
        {
            var prefix = UpperSnake(component.Kind);
            MoonConstant(b, $"{prefix}_KIND", "String", System.Text.Json.JsonSerializer.Serialize(component.Kind));
            foreach (var flag in component.Flags.OrderBy(pair => pair.Key, StringComparer.Ordinal))
                MoonConstant(b, $"{prefix}_FLAG_{UpperSnake(flag.Key)}", "UInt", (1U << flag.Value) + "U");
            foreach (var command in component.Commands.OrderBy(pair => pair.Key, StringComparer.Ordinal))
                MoonConstant(b, $"{prefix}_COMMAND_{UpperSnake(command.Key)}", "Int", command.Value.Id.ToString());
            foreach (var controlEvent in component.Events.OrderBy(pair => pair.Key, StringComparer.Ordinal))
                MoonConstant(b, $"{prefix}_EVENT_{UpperSnake(controlEvent.Key)}", "Int", controlEvent.Value.Id.ToString());
        }
        return b.ToString().TrimEnd() + "\n";
    }
}
